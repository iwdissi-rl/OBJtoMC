#!/usr/bin/env python3
"""
dissect_region.py — one-off research tool.

Reads a Minecraft Java Edition Anvil region file (`r.X.Z.mca`) and prints a
Markdown dissection of its on-disk layout to stdout. Used in Session 8 to
produce `research/anvil_ground_truth.md` against the maintainer-supplied
MC 1.21.5 Superflat fixture at
`tests/fixtures/real_minecraft_1.21.5_flat_r.0.0.mca`.

Not hooked into CTest; not a unit test; not part of the build. Pure research
artefact, re-runnable from the command line.

Usage:
    tests/oracle_venv/bin/python tests/dissect/dissect_region.py <PATH_TO_MCA>

Dependencies (already pinned in `tests/oracle_venv/`):
    - NBT==1.5.1                  (twoolie/NBT, used for chunk-NBT parsing)
    - anvil-parser==0.9.0         (matcool/anvil-parser, used to cross-check
                                   the chunk-x/chunk-z index formula)
"""

from __future__ import annotations

import datetime
import hashlib
import io
import os
import sys
import zlib

import anvil  # type: ignore[import-untyped]
import nbt.nbt  # type: ignore[import-untyped]

SECTOR_SIZE = 4096
HEADER_SECTORS = 2  # location table + timestamp table = 8192 bytes = 2 sectors

COMPRESSION_SCHEMES = {
    1: "gzip",
    2: "zlib",
    3: "uncompressed",
    4: "lz4",
}


def emit(line: str = "") -> None:
    print(line)


def main(path: str) -> int:
    with open(path, "rb") as f:
        data = f.read()
    size = len(data)

    digest = hashlib.sha256(data).hexdigest()

    emit("# Anvil Region-File Dissection")
    emit("")
    emit(
        f"Auto-generated by `tests/dissect/dissect_region.py`. Re-run with "
        f"`tests/oracle_venv/bin/python tests/dissect/dissect_region.py "
        f"<path-to-.mca>` to refresh."
    )
    emit("")
    emit("## File")
    emit("")
    emit(f"- **Path:** `{path}`")
    emit(f"- **Size:** {size} bytes")
    if size % SECTOR_SIZE == 0:
        emit(
            f"- **4 KiB alignment:** OK (size = {size // SECTOR_SIZE} × "
            f"{SECTOR_SIZE})"
        )
    else:
        emit(
            f"- **4 KiB alignment:** ❌ NOT 4 KiB-aligned "
            f"(size mod 4096 = {size % SECTOR_SIZE})"
        )
    emit(f"- **SHA-256:** `{digest}`")
    emit("")

    if size < SECTOR_SIZE * HEADER_SECTORS:
        emit(f"❌ File too small to contain the 8 KiB header. Aborting.")
        return 2

    # -------------------- LOCATION TABLE (bytes 0..4095) --------------------
    emit("## Location Table (bytes 0..4095)")
    emit("")
    emit(
        "Each of the 1024 entries is 4 bytes: 3 bytes BE sector_offset "
        "(in 4 KiB units, relative to file start), 1 byte sector_count "
        "(in 4 KiB units, rounded up). Empty chunks have both fields = 0."
    )
    emit("")
    emit("Index formula: `entry_index = (chunk_x & 31) + (chunk_z & 31) * 32`.")
    emit("")

    populated: list[tuple[int, int, int, int]] = []
    # (chunk_x, chunk_z, sector_offset, sector_count)
    total_sectors_used = 0
    for entry_index in range(1024):
        b_off = entry_index * 4
        sector_offset = int.from_bytes(data[b_off : b_off + 3], "big")
        sector_count = data[b_off + 3]
        if sector_offset == 0 and sector_count == 0:
            continue
        chunk_x = entry_index % 32
        chunk_z = entry_index // 32
        populated.append((chunk_x, chunk_z, sector_offset, sector_count))
        total_sectors_used += sector_count

    emit(f"- **Populated chunks:** {len(populated)} / 1024")
    emit(f"- **Total sectors used by chunk payloads:** {total_sectors_used} "
         f"× 4 KiB = {total_sectors_used * SECTOR_SIZE} bytes")
    emit(
        f"- **Sectors occupied (incl. 2-sector header):** "
        f"{total_sectors_used + HEADER_SECTORS}; file has "
        f"{size // SECTOR_SIZE} sectors."
    )
    emit("")

    if not populated:
        emit("❌ Zero populated chunks — fixture is empty or wrong version. "
             "Aborting.")
        return 3

    # Cross-check chunk indexing formula against anvil-parser.
    region = anvil.Region.from_file(path)
    mismatches = 0
    for chunk_x, chunk_z, sector_offset, sector_count in populated:
        ap_off, ap_count = region.chunk_location(chunk_x, chunk_z)
        if (ap_off, ap_count) != (sector_offset, sector_count):
            mismatches += 1
    if mismatches == 0:
        emit(
            f"- **Cross-check vs `anvil-parser==0.9.0`:** all "
            f"{len(populated)} populated entries agree on (sector_offset, "
            f"sector_count). Index formula confirmed."
        )
    else:
        emit(
            f"- **Cross-check vs `anvil-parser==0.9.0`:** ❌ "
            f"{mismatches} mismatches!"
        )
    emit("")

    emit(
        "Populated (chunk_x, chunk_z, sector_offset, sector_count) — first "
        "16 entries (sorted by linear index):"
    )
    emit("")
    emit("| chunk_x | chunk_z | sector_offset | sector_count |")
    emit("|---------|---------|---------------|--------------|")
    for chunk_x, chunk_z, sec_off, sec_cnt in populated[:16]:
        emit(f"| {chunk_x} | {chunk_z} | {sec_off} | {sec_cnt} |")
    if len(populated) > 16:
        emit(f"| … | … | … | … |")
        emit(f"| (showing 16 of {len(populated)}) | | | |")
    emit("")

    # -------------------- TIMESTAMP TABLE (bytes 4096..8191) ----------------
    emit("## Timestamp Table (bytes 4096..8191)")
    emit("")
    emit(
        "Each of the 1024 entries is a 4-byte BE int32 epoch-seconds "
        "last-modification time. Same index formula as the location table."
    )
    emit("")

    timestamps: list[tuple[int, int, int]] = []
    # (chunk_x, chunk_z, epoch)
    for chunk_x, chunk_z, _sec_off, _sec_cnt in populated:
        entry_index = chunk_x + chunk_z * 32
        b_off = SECTOR_SIZE + entry_index * 4
        epoch = int.from_bytes(data[b_off : b_off + 4], "big", signed=False)
        timestamps.append((chunk_x, chunk_z, epoch))

    epochs = [e for _, _, e in timestamps]
    e_min, e_max = min(epochs), max(epochs)
    iso_min = datetime.datetime.fromtimestamp(
        e_min, datetime.timezone.utc
    ).isoformat()
    iso_max = datetime.datetime.fromtimestamp(
        e_max, datetime.timezone.utc
    ).isoformat()
    emit(f"- **Populated timestamps:** {len(timestamps)}")
    emit(f"- **Range:** {e_min} .. {e_max} ({iso_min} .. {iso_max})")
    emit("")
    emit("First 8 (chunk_x, chunk_z, timestamp, UTC ISO):")
    emit("")
    emit("| chunk_x | chunk_z | epoch | UTC ISO |")
    emit("|---------|---------|-------|---------|")
    for chunk_x, chunk_z, epoch in timestamps[:8]:
        iso = datetime.datetime.fromtimestamp(
            epoch, datetime.timezone.utc
        ).isoformat()
        emit(f"| {chunk_x} | {chunk_z} | {epoch} | {iso} |")
    emit("")

    # -------------------- FIRST CHUNK PAYLOAD FRAMING -----------------------
    emit("## First Populated Chunk — Payload Framing")
    emit("")
    chunk_x, chunk_z, sec_off, sec_cnt = populated[0]
    sec_byte_off = sec_off * SECTOR_SIZE
    emit(f"- **Chunk:** (x={chunk_x}, z={chunk_z})")
    emit(
        f"- **Sector offset:** {sec_off} (= byte offset {sec_byte_off}); "
        f"sector count: {sec_cnt} (= {sec_cnt * SECTOR_SIZE} bytes reserved)"
    )

    if sec_byte_off + 5 > size:
        emit("❌ Sector offset points past end of file. Aborting.")
        return 4

    declared_length = int.from_bytes(
        data[sec_byte_off : sec_byte_off + 4], "big", signed=False
    )
    compression_byte = data[sec_byte_off + 4]
    scheme_name = COMPRESSION_SCHEMES.get(
        compression_byte, f"unknown ({compression_byte})"
    )
    emit(f"- **Declared length (BE int32):** {declared_length} bytes "
         f"(this includes the 1-byte compression scheme, excludes itself)")
    emit(f"- **Compression scheme byte:** {compression_byte} ({scheme_name})")

    if compression_byte != 2:
        emit("")
        emit(
            f"⚠️ **Compression scheme is NOT 2 (zlib).** Project-level "
            f"decision: v0.1 supports only scheme 2. Found scheme "
            f"{compression_byte} ({scheme_name}). STOP."
        )
        return 5

    compressed_payload_start = sec_byte_off + 5
    compressed_payload_end = sec_byte_off + 4 + declared_length
    compressed_bytes = data[compressed_payload_start:compressed_payload_end]
    emit(
        f"- **Compressed payload span:** bytes "
        f"{compressed_payload_start}..{compressed_payload_end - 1} "
        f"({len(compressed_bytes)} bytes, = declared_length − 1)"
    )

    decompressed = zlib.decompress(compressed_bytes)
    emit(f"- **Decompressed size:** {len(decompressed)} bytes")
    emit(
        f"- **Decompressed SHA-256:** "
        f"`{hashlib.sha256(decompressed).hexdigest()}`"
    )
    emit(
        f"- **Compression ratio:** "
        f"{len(compressed_bytes) / len(decompressed):.3f} "
        f"({len(compressed_bytes)} / {len(decompressed)})"
    )
    emit("")

    # Parse decompressed bytes as NBT.
    nbt_file = nbt.nbt.NBTFile(buffer=io.BytesIO(decompressed))

    emit("### Top-Level Compound Keys")
    emit("")
    emit("| Key | NBT tag id | Tag class |")
    emit("|-----|------------|-----------|")
    for child in nbt_file.tags:
        emit(f"| `{child.name}` | {child.id} | `{type(child).__name__}` |")
    emit("")

    # DataVersion
    if "DataVersion" not in nbt_file:
        emit("❌ Chunk has no `DataVersion` key. Aborting.")
        return 6
    data_version = nbt_file["DataVersion"].value
    emit(f"- **`DataVersion`:** {data_version} "
         f"(expected 4325 for MC 1.21.5)")
    if data_version != 4325:
        emit(
            f"⚠️ **DataVersion mismatch:** got {data_version}, expected 4325. "
            f"maintainer-supplied fixture is the wrong MC version. STOP."
        )
        return 7

    # Positional fields
    x_pos = nbt_file["xPos"].value if "xPos" in nbt_file else None
    y_pos = nbt_file["yPos"].value if "yPos" in nbt_file else None
    z_pos = nbt_file["zPos"].value if "zPos" in nbt_file else None
    emit(f"- **`xPos`:** {x_pos} (chunk_x from location-table index = "
         f"{chunk_x}; match: {x_pos == chunk_x})")
    emit(
        f"- **`yPos`:** {y_pos} (expected -4 for MC 1.21.5: world Y=-64..320 "
        f"= 24 sections starting at section index -4)"
    )
    emit(f"- **`zPos`:** {z_pos} (chunk_z from location-table index = "
         f"{chunk_z}; match: {z_pos == chunk_z})")

    # Status
    status = nbt_file["Status"].value if "Status" in nbt_file else None
    emit(f"- **`Status`:** `{status}` "
         f"(expected `minecraft:full` for a fully-generated chunk)")

    # Sections list
    if "sections" not in nbt_file:
        emit("❌ Chunk has no `sections` list. Aborting.")
        return 8
    sections = nbt_file["sections"]
    emit(f"- **`sections` list length:** {len(sections)} "
         f"(expected 24 for MC 1.21.5)")
    emit("")

    # -------------------- FIRST NON-EMPTY SECTION ---------------------------
    emit("### First Non-Empty Section (palette inspection)")
    emit("")

    def section_palette(sec) -> list[str] | None:
        # sec is a TAG_Compound; look for block_states.palette
        if "block_states" not in sec:
            return None
        bs = sec["block_states"]
        if "palette" not in bs:
            return None
        pal = bs["palette"]
        names = []
        for entry in pal:
            if "Name" in entry:
                names.append(str(entry["Name"].value))
            else:
                names.append("<no-Name>")
        return names

    chosen = None
    for sec in sections:
        pal = section_palette(sec)
        if pal is None:
            continue
        non_air = [n for n in pal if n != "minecraft:air"]
        if non_air:
            chosen = (sec, pal)
            break
    if chosen is None:
        # fall back to first section that has any palette
        for sec in sections:
            pal = section_palette(sec)
            if pal is not None:
                chosen = (sec, pal)
                break

    if chosen is None:
        emit("No section has a `block_states.palette` field.")
    else:
        sec, pal = chosen
        sec_y = sec["Y"].value if "Y" in sec else "?"
        emit(f"- **Section Y:** {sec_y}")
        emit(f"- **Palette size:** {len(pal)}")
        emit("- **Palette entries:**")
        for i, name in enumerate(pal):
            emit(f"  {i}. `{name}`")
    emit("")

    # -------------------- INTRA-SECTOR PADDING (first chunk) ----------------
    emit("### Padding Inspection")
    emit("")
    emit(
        "Each chunk's compressed payload ends at byte "
        "`sector_start + 4 + declared_length` but its allocated sectors "
        "extend to `(sector_offset + sector_count) * 4096`. The trailing "
        "region is intra-sector padding — Minecraft's chunk writer is free "
        "to leave any contents there."
    )
    emit("")
    payload_end = sec_byte_off + 4 + declared_length
    allocated_end = (sec_off + sec_cnt) * SECTOR_SIZE
    pad_len = allocated_end - payload_end
    emit(
        f"- **First chunk allocated end:** byte {allocated_end} "
        f"({sec_cnt} sector(s) × 4096)"
    )
    emit(
        f"- **First chunk payload ends at byte {payload_end} "
        f"(4-byte length prefix + {declared_length} payload bytes)**"
    )
    emit(f"- **Intra-sector padding length:** {pad_len} bytes")
    if pad_len > 0:
        peek_n = min(32, pad_len)
        peek = data[payload_end : payload_end + peek_n]
        hex_peek = " ".join(f"{b:02x}" for b in peek)
        all_zero_peek = all(b == 0 for b in peek)
        emit(
            f"- **First {peek_n} padding bytes:** `{hex_peek}`"
            + (" (all zero)" if all_zero_peek else " (non-zero observed)")
        )
        # Scan all populated chunks' padding for non-zero bytes.
        non_zero_padding_chunks = 0
        for cx, cz, so, sc in populated:
            sbo = so * SECTOR_SIZE
            if sbo + 5 > size:
                continue
            dl = int.from_bytes(data[sbo : sbo + 4], "big")
            pe = sbo + 4 + dl
            ae = (so + sc) * SECTOR_SIZE
            if pe < ae and any(b != 0 for b in data[pe:ae]):
                non_zero_padding_chunks += 1
        emit(
            f"- **Across all {len(populated)} populated chunks:** "
            f"{non_zero_padding_chunks} chunks have non-zero bytes in their "
            f"intra-sector padding region "
            f"({'mixed' if non_zero_padding_chunks not in (0, len(populated)) else 'uniform'})."
        )

    # -------------------- POST-LAST-CHUNK TAIL ------------------------------
    emit("")
    emit("### Tail After Last Populated Chunk")
    emit("")
    last_chunk = max(populated, key=lambda t: t[2] + t[3])
    last_x, last_z, last_off, last_cnt = last_chunk
    last_end_byte = (last_off + last_cnt) * SECTOR_SIZE
    emit(
        f"- **Last chunk (by end-of-sectors):** (x={last_x}, z={last_z}) at "
        f"sector {last_off}, count {last_cnt}; sectors end at byte "
        f"{last_end_byte}; file size {size}"
    )
    if last_end_byte >= size:
        emit(
            "- **No bytes after last chunk's sectors** — the file is "
            "tightly packed; the last allocated sector is also the last "
            "sector of the file."
        )
    else:
        peek = data[last_end_byte : last_end_byte + 32]
        hex_peek = " ".join(f"{b:02x}" for b in peek)
        all_zero = all(b == 0 for b in peek)
        emit(
            f"- **Bytes [{last_end_byte}..{last_end_byte + len(peek)}):** "
            f"`{hex_peek}`"
        )
        emit(
            f"- **All zero?** {all_zero} "
            f"({'pure zero padding' if all_zero else 'non-zero — next chunk header or in-sector padding'})"
        )

    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.stderr.write(
            f"usage: {sys.argv[0]} <path-to-region.mca>\n"
        )
        sys.exit(1)
    if not os.path.exists(sys.argv[1]):
        sys.stderr.write(f"error: file not found: {sys.argv[1]}\n")
        sys.exit(1)
    sys.exit(main(sys.argv[1]))
